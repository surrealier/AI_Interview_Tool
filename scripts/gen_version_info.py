"""Emit a PyInstaller VSVersionInfo file from ai_interviewer.__version__.

Usage: python scripts/gen_version_info.py [output_path]
Default output: build_version_info.txt in the project root (gitignored).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from ai_interviewer import __version__  # noqa: E402
from ai_interviewer.release_check import display_version  # noqa: E402

COMPANY = "Surrealier"
PRODUCT = "AI Interviewer"
DESCRIPTION = "AI Interviewer - offline interview practice studio"
EXE_NAME = "AIInterview.exe"


def numeric_version(version: str) -> tuple[int, int, int, int]:
    match = re.match(r"^(\d+)\.(\d+)\.(\d+)", version)
    if not match:
        return (0, 0, 0, 0)
    major, minor, patch = (int(part) for part in match.groups())
    return (major, minor, patch, 0)


TEMPLATE = """# Generated by scripts/gen_version_info.py - do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vers},
    prodvers={vers},
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          "040904B0",
          [
            StringStruct("CompanyName", "{company}"),
            StringStruct("FileDescription", "{description}"),
            StringStruct("FileVersion", "{display}"),
            StringStruct("InternalName", "{exe}"),
            StringStruct("LegalCopyright", "Copyright (c) {company}"),
            StringStruct("OriginalFilename", "{exe}"),
            StringStruct("ProductName", "{product}"),
            StringStruct("ProductVersion", "{display}"),
          ],
        ),
        StringTable(
          "041204B0",
          [
            StringStruct("CompanyName", "{company}"),
            StringStruct("FileDescription", "{description}"),
            StringStruct("FileVersion", "{display}"),
            StringStruct("InternalName", "{exe}"),
            StringStruct("LegalCopyright", "Copyright (c) {company}"),
            StringStruct("OriginalFilename", "{exe}"),
            StringStruct("ProductName", "{product}"),
            StringStruct("ProductVersion", "{display}"),
          ],
        ),
      ]
    ),
    VarFileInfo([VarStruct("Translation", [1033, 1200, 1042, 1200])]),
  ],
)
"""


def main() -> None:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else PROJECT_ROOT / "build_version_info.txt"
    content = TEMPLATE.format(
        vers=numeric_version(__version__),
        display=display_version(),
        company=COMPANY,
        product=PRODUCT,
        description=DESCRIPTION,
        exe=EXE_NAME,
    )
    output.write_text(content, encoding="utf-8")
    print(f"wrote {output} ({display_version()})")


if __name__ == "__main__":
    main()
