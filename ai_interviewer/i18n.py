from __future__ import annotations

import locale


SUPPORTED_UI_LANGUAGES = ("ko", "en")

_current_language = "ko"


def resolve_system_ui_language() -> str:
    """Pick the default UI language from the Windows/user locale."""
    try:
        name = locale.getlocale()[0] or ""
    except Exception:
        name = ""
    lowered = str(name).lower()
    if lowered.startswith("ko") or "korean" in lowered:
        return "ko"
    return "en"


def set_language(language: str) -> None:
    global _current_language
    _current_language = language if language in SUPPORTED_UI_LANGUAGES else "en"


def get_language() -> str:
    return _current_language


def tr(key: str, **fmt: object) -> str:
    catalog = _CATALOGS.get(_current_language, EN)
    text = catalog.get(key) or EN.get(key) or key
    if fmt:
        try:
            return text.format(**fmt)
        except (KeyError, IndexError):
            return text
    return text


def ui_language_label(language: str) -> str:
    return tr(f"lang.ui.{language}")


